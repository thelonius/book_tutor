# Порядок показа в интерфейсе. Словарь бы не помог: jsonify сортирует
# ключи по алфавиту, и «Эпоха» вылезала на второе место.
MODE_ORDER = ('discuss', 'quiz', 'context', 'search')

CHAPTER_MODES = ('discuss', 'quiz', 'context')


def chapter_prompt(mode: str, book_title: str, chapter: dict, text: str,
                   notes: str = '') -> str:
    """Системный промпт для режима, привязанного к главе."""
    template = {'discuss': DISCUSS, 'quiz': QUIZ, 'context': CONTEXT}[mode]
    subtitle = f'\n{chapter["subtitle"]}' if chapter.get('subtitle') else ''
    prompt = template.format(
        book=book_title, idx=chapter['idx'], title=chapter['title'],
        subtitle=subtitle, text=text, grounding=GROUNDING, style=STYLE)
    if notes:
        prompt += (f'\n\nЗАМЕТКИ ЧИТАТЕЛЯ К ЭТОЙ ГЛАВЕ (его собственные, '
                   f'не из книги — учитывай их и можешь на них ссылаться):\n{notes}')
    return prompt


def search_prompt(context: str) -> str:
    return SEARCH.format(context=context, grounding=GROUNDING, style=STYLE)


